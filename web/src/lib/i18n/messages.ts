export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, hi };

export type MessageValues = Record<string, ReactNode>;

const PLACEHOLDER = /\{(\w+)\}/g;

/** The message with its values filled in: plain text when every value is text. */
export function formatMessage(template: string, values?: MessageValues): ReactNode {
  if (!values) return template;
  const parts: ReactNode[] = [];
  let last = 0;
  let plain = true;
  for (const match of template.matchAll(PLACEHOLDER)) {
    const index = match.index ?? 0;
    if (index > last) parts.push(template.slice(last, index));
    const value = values[match[1]];
    if (value !== null && typeof value === "object") plain = false;
    parts.push(value ?? match[0]);
    last = index + match[0].length;
  }
  if (last < template.length) parts.push(template.slice(last));
  if (plain) return parts.join("");
  return parts.map((part, i) => createElement(Fragment, { key: i }, part));
}

/** The message as a string, for attributes and announcements. */
export function messageText(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const template = MESSAGES[locale][key];
  return values ? template.replace(PLACEHOLDER, (whole, name: string) => String(values[name] ?? whole)) : template;
}
